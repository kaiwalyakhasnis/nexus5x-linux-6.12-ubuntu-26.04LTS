#!/usr/bin/env python3
"""Turn the gamma tables of the Nexus 5X's 3.10 panel device tree
(arch/arm64/boot/dts/lge/dsi-panel-jd35695b-1080p-cmd.dtsi) into a C header
for panel-lg-bullhead-jd35695b.c.

Every gamma command there is a generic short write with two bytes (dtype
0x23, no wait), so each table is a flat list of byte pairs.

usage: gen-jd35695b-gamma.py <dsi-panel-jd35695b-1080p-cmd.dtsi> > header
"""
import re, sys

VARIANTS = [("", "default"), ("_type00", "type00"), ("_type10", "type10")]

src = open(sys.argv[1]).read()
print("/* SPDX-License-Identifier: GPL-2.0-only */")
print("/*")
print(" * JD35695B gamma tables of the Nexus 5X, generated by")
print(" * bullhead-linux tools/gen-jd35695b-gamma.py from the 3.10 kernel's")
print(" * dsi-panel-jd35695b-1080p-cmd.dtsi (qcom,mdss-dsi-gamma-default):")
print(" * Copyright (c) 2015, The Linux Foundation. All rights reserved.")
print(" * Pairs of (register, value), sent as generic short writes.")
print(" */")
for suffix, name in VARIANTS:
    node = re.search(r"dsi_jd35695b_1080p_cmd%s: .*?\n\t};" % suffix, src, re.S).group(0)
    raw = bytes.fromhex("".join(re.search(
        r"qcom,mdss-dsi-gamma-default = \[(.*?)\];", node, re.S).group(1).split()))
    pairs, i = [], 0
    while i < len(raw):
        dtype, _last, _vc, _ack, wait, hi, lo = raw[i:i + 7]
        n = hi << 8 | lo
        assert dtype == 0x23 and wait == 0 and n == 2, (name, i)
        pairs.append(raw[i + 7:i + 9])
        i += 7 + n
    print("\nstatic const u8 jd35695b_gamma_%s[][2] = {" % name)
    for k in range(0, len(pairs), 6):
        print("\t" + " ".join("{ 0x%02x, 0x%02x }," % (p[0], p[1]) for p in pairs[k:k + 6]))
    print("};")
