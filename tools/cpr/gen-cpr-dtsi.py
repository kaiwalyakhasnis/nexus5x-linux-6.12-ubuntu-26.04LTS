#!/usr/bin/env python3
"""Generate dts/bullhead-cpr.dtsi from the 3.10 qcom/msm8992-regulator.dtsi:
the CPR nodes (only the properties cpr-8992.c reads, copied verbatim) and the
CPU OPP tables (every stock rate, ceiling voltage as placeholder until the
CPR driver puts in the fused open-loop value, MX corner per fuse corner).

usage: gen-cpr-dtsi.py msm8992-regulator.dtsi > dts/bullhead-cpr.dtsi
"""
import re
import sys

PROPS = [
    'qcom,cpr-fuse-corners', 'qcom,cpr-apc-volt-step',
    'qcom,cpr-voltage-ceiling', 'qcom,cpr-voltage-floor',
    'qcom,cpr-fuse-row', 'qcom,cpr-fuse-ro-sel', 'qcom,cpr-fuse-init-voltage',
    'qcom,cpr-fuse-revision', 'qcom,speed-bin-fuse-sel',
    'qcom,cpr-fuse-redun-sel', 'qcom,cpr-init-voltage-ref',
    'qcom,cpr-init-voltage-step', 'qcom,cpr-corner-map',
    'qcom,cpr-voltage-ceiling-override', 'qcom,cpr-voltage-floor-override',
    'qcom,cpr-fuse-version-map', 'qcom,cpr-init-voltage-adjustment',
    'qcom,cpr-voltage-scaling-factor-max', 'qcom,cpr-corner-frequency-map',
    'qcom,cpr-speed-bin-max-corners',
]
FLAGS = ['qcom,cpr-scaled-init-voltage-as-ceiling']
# 3.10 RPM corners (qcom,vdd-mx-corner-map) -> mainline msm8994 rpmpd levels
MX = {3: 'rpmpd_opp_svs_krait', 4: 'rpmpd_opp_svs_soc', 5: 'rpmpd_opp_nom',
      6: 'rpmpd_opp_turbo', 7: 'rpmpd_opp_super_turbo'}
# cluster: 3.10 node, reg, speed bin of this phone's family table, CPUs
CLUSTERS = [
    ('apc0', 'apc0_vreg_corner', 0, ['CPU0', 'CPU1', 'CPU2', 'CPU3']),
    ('apc1', 'apc1_vreg_corner', 1, ['CPU4', 'CPU5']),
]


def node(src, label):
    i = src.index(label + ':')
    return src[i:src.index('\n\t};', i)]


def nums(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return [int(t.strip('() ').replace(' ', ''), 0)
            for t in re.findall(r'\(\s*-?\s*\w+\s*\)|-?0x[0-9a-fA-F]+|-?\d+', text)]


def get(n, p):
    m = re.search(re.escape(p) + r'\s*=\s*([^;]*);', n)
    return m


src = open(sys.argv[1]).read()
out = ['// SPDX-License-Identifier: GPL-2.0-only',
       '/* Generated by tools/cpr/gen-cpr-dtsi.py from the 3.10 msm8992-regulator.dtsi */',
       '']
for name, label, cl, cpus in CLUSTERS:
    n = node(src, label)
    reg = re.search(r'reg\s*=\s*<(0x[0-9a-f]+)', n).group(1)
    out += ['&soc {', f'\tcpr_{name}: cpr@{reg[2:]} ' + '{',
            '\t\tcompatible = "qcom,msm8992-cpr";',
            f'\t\treg = <{reg} 0x1000>, <0xfc4bc000 0x1000>;',
            '\t\treg-names = "rbcpr", "efuse";',
            f'\t\tqcom,cpus = {", ".join("<&" + c + ">" for c in cpus)};']
    if name == 'apc0':
        # the CCI shares the A53 rail: 3.10 msm8992.dtsi qcom,cci-speedbin0-v0
        out += ['\t\tclocks = <&cpu_clk 2>;', '\t\tclock-names = "cci";',
                '\t\tqcom,cci-corner-map = <134400000 2>, <300000000 4>,',
                '\t\t\t<384000000 6>, <556800000 6>, <600000000 8>,',
                '\t\t\t<729600000 8>, <787200000 9>;']
    for p in PROPS:
        m = get(n, p)
        if m:
            out.append('\t\t' + p + ' = ' + re.sub(r'\n\s*', '\n\t\t\t', m.group(1).strip()) + ';')
    for f in FLAGS:
        if re.search(re.escape(f) + r'\s*;', n):
            out.append('\t\t' + f + ';')
    out += ['\t};', '};', '']

    # OPP table: corners with a frequency, ceiling override, mx map
    cmap = nums(get(n, 'qcom,cpr-corner-map').group(1))
    fmap = nums(get(n, 'qcom,cpr-corner-frequency-map').group(1))
    freq = {fmap[i]: fmap[i + 1] for i in range(0, len(fmap), 2)}
    ceil = nums(get(n, 'qcom,cpr-voltage-ceiling-override').group(1))[2:]
    floor = nums(get(n, 'qcom,cpr-voltage-floor-override').group(1))[2:]
    mx = nums(get(n, 'qcom,vdd-mx-corner-map').group(1))
    out += ['/ {', f'\tcluster{cl}_opp: opp-table-cluster{cl} ' + '{',
            '\t\tcompatible = "operating-points-v2";', '\t\topp-shared;', '']
    seen = set()
    for corner in sorted(freq):
        hz = freq[corner]
        if hz < 384000000 or hz in seen:     # 300 MHz is not a cpufreq rate
            continue
        seen.add(hz)
        fc = cmap[corner - 1]
        v_ceil, v_floor = ceil[corner - 1], floor[corner - 1]
        out += [f'\t\topp-{hz} ' + '{',
                f'\t\t\topp-hz = /bits/ 64 <{hz}>;',
                f'\t\t\topp-microvolt = <{v_ceil} {v_floor} {v_ceil}>;',
                f'\t\t\trequired-opps = <&{MX[mx[fc - 1]]}>;',
                '\t\t};']
    out += ['\t};', '};', '']
print('\n'.join(out))
